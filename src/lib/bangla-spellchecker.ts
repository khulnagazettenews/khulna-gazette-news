export interface SpellCheckResult {
  word: string;
  isCorrect: boolean;
  suggestions: string[];
}

function getRootWord(word: string): string {
  let stemmed = word;
  for (const suffix of BANGLA_SUFFIXES) {
    if (stemmed.length > suffix.length + 2 && stemmed.endsWith(suffix)) {
      stemmed = stemmed.slice(0, -suffix.length);
      break;
    }
  }
  return stemmed;
}

function generatePhoneticVariations(word: string): string[] {
  const variations = new Set<string>();

  const rules = [
    { from: 'ু', to: 'ূ' },
    { from: 'ূ', to: 'ু' },
    { from: 'ি', to: 'ী' },
    { from: 'ী', to: 'ি' },
    { from: 'ষ্ট', to: 'ষ্ঠ' },
    { from: 'ষ্ঠ', to: 'ষ্ট' },
    { from: 'ন', to: 'ণ' },
    { from: 'ণ', to: 'ন' },
    { from: 'শ', to: 'ষ' },
    { from: 'ষ', to: 'স' },
    { from: 'স', to: 'শ' },
    { from: 'ড়', to: 'র' },
    { from: 'র', to: 'ড়' },
    { from: 'ত', to: 'ত্ব' },
  ];

  rules.forEach(({ from, to }) => {
    if (word.includes(from)) {
      const swapped = word.replaceAll(from, to);
      variations.add(swapped);
    }
  });

  return Array.from(variations);
}

export function checkBanglaWordSpelling(word: string): SpellCheckResult {
  const cleanWord = word.replace(/[।,\.?!;:'"“”‘’\(\)\[\]\{\}\s]/g, '').trim();
  
  if (!cleanWord || cleanWord.length <= 1) {
    return { word: cleanWord, isCorrect: true, suggestions: [] };
  }

  // 1. Direct Known Typo Match
  if (BANGLA_COMMON_TYPOS[cleanWord]) {
    return {
      word: cleanWord,
      isCorrect: false,
      suggestions: [BANGLA_COMMON_TYPOS[cleanWord]],
    };
  }

  // Check typos with suffix (e.g., "আইনজীবিরা" -> root typo "আইনজীবি" + "রা")
  const rootForTypo = getRootWord(cleanWord);
  if (BANGLA_COMMON_TYPOS[rootForTypo]) {
    const correctedRoot = BANGLA_COMMON_TYPOS[rootForTypo];
    const suffix = cleanWord.slice(rootForTypo.length);
    return {
      word: cleanWord,
      isCorrect: false,
      suggestions: [correctedRoot + suffix],
    };
  }

  // 2. Direct dictionary hit or valid numbers
  if (BANGLA_DICTIONARY.has(cleanWord) || /^[০-৯]+$/.test(cleanWord) || /^[0-9]+$/.test(cleanWord)) {
    return { word: cleanWord, isCorrect: true, suggestions: [] };
  }

  // 3. Root word match after suffix removal
  const root = getRootWord(cleanWord);
  if (BANGLA_DICTIONARY.has(root)) {
    return { word: cleanWord, isCorrect: true, suggestions: [] };
  }

  // 4. Search candidates using Levenshtein & Phonetic Swaps
  const candidatesMap = new Map<string, number>();

  const phoneticVars = generatePhoneticVariations(cleanWord);
  phoneticVars.forEach((v) => {
    if (BANGLA_COMMON_TYPOS[v]) {
      candidatesMap.set(BANGLA_COMMON_TYPOS[v], 1);
    }
    if (BANGLA_DICTIONARY.has(v) || BANGLA_DICTIONARY.has(getRootWord(v))) {
      candidatesMap.set(v, 1);
    }
  });

  BANGLA_DICTIONARY.forEach((dictWord) => {
    if (Math.abs(dictWord.length - cleanWord.length) <= 3) {
      const dist = getLevenshteinDistance(cleanWord, dictWord);
      if (dist <= 3) {
        const existing = candidatesMap.get(dictWord);
        if (!existing || dist < existing) {
          candidatesMap.set(dictWord, dist);
        }
      }
    }
  });

  const sortedCandidates = Array.from(candidatesMap.entries())
    .sort((a, b) => a[1] - b[1])
    .map(([w]) => w)
    .slice(0, 5);

  return {
    word: cleanWord,
    isCorrect: false,
    suggestions: sortedCandidates,
  };
}

export function checkBanglaTextSpelling(text: string): SpellCheckResult[] {
  if (!text) return [];

  const words = text.match(/[\u0980-\u09FF]+/g) || [];
  const uniqueWords = Array.from(new Set(words));
  
  const results: SpellCheckResult[] = [];
  for (const w of uniqueWords) {
    const res = checkBanglaWordSpelling(w);
    if (!res.isCorrect) {
      results.push(res);
    }
  }

  return results;
}
